function t_b58check_encode($versionPrefix, $hash) {
	$payload = $versionPrefix . $hash;
	$full = $payload . substr(hash('sha256', hash('sha256', $payload, true), true), 0, 4);

	$alphabet = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
	$digits = array(0);
	for ($i = 0, $len = strlen($full); $i < $len; $i++) {
		$carry = ord($full[$i]);
		for ($j = 0, $n = count($digits); $j < $n; $j++) {
			$carry += $digits[$j] << 8;
			$digits[$j] = $carry % 58;
			$carry = intdiv($carry, 58);
		}
		while ($carry > 0) {
			$digits[] = $carry % 58;
			$carry = intdiv($carry, 58);
		}
	}
	$out = '';
	for ($i = 0; $i < strlen($full) && $full[$i] === "\x00"; $i++) {
		$out .= '1';
	}
	for ($i = count($digits) - 1; $i >= 0; $i--) {
		$out .= $alphabet[$digits[$i]];
	}
	return $out;
}

function t_bech32_polymod($values) {
	$gen = array(0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3);
	$chk = 1;
	foreach ($values as $v) {
		$top = $chk >> 25;
		$chk = (($chk & 0x1ffffff) << 5) ^ $v;
		for ($i = 0; $i < 5; $i++) {
			if (($top >> $i) & 1) {
				$chk ^= $gen[$i];
			}
		}
	}
	return $chk;
}

function t_bech32_encode($hrp, $witnessVersion, $programBytes, $useBech32m) {
	$charset = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l';

	// 8-bit -> 5-bit with padding
	$data = array($witnessVersion);
	$acc = 0; $bits = 0;
	for ($i = 0, $len = strlen($programBytes); $i < $len; $i++) {
		$acc = ($acc << 8) | ord($programBytes[$i]);
		$bits += 8;
		while ($bits >= 5) {
			$bits -= 5;
			$data[] = ($acc >> $bits) & 31;
		}
	}
	if ($bits > 0) {
		$data[] = ($acc << (5 - $bits)) & 31;
	}

	$hrpExp = array();
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) >> 5; }
	$hrpExp[] = 0;
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) & 31; }

	$const = $useBech32m ? 0x2bc830a3 : 1;
	$poly = t_bech32_polymod(array_merge($hrpExp, $data, array(0, 0, 0, 0, 0, 0))) ^ $const;
	$checksum = array();
	for ($i = 0; $i < 6; $i++) {
		$checksum[] = ($poly >> (5 * (5 - $i))) & 31;
	}

	$out = $hrp . '1';
	foreach (array_merge($data, $checksum) as $d) {
		$out .= $charset[$d];
	}
	return $out;
}

// Generic bech32/bech32m encoder with NO witness-version byte, for the
// encodings that borrow the bech32 string format without being segwit
// (Zcash Sapling 'zs' = bech32, Zcash Unified 'u' = bech32m). t_bech32_encode
// above always prepends a witness version and so cannot produce these.
// Self-checked below against the published all-zero Sapling address.
function t_bech32_raw_encode($hrp, $payloadBytes, $useBech32m) {
	$charset = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l';

	// 8-bit -> 5-bit with padding
	$data = array(); $acc = 0; $bits = 0;
	for ($i = 0, $len = strlen($payloadBytes); $i < $len; $i++) {
		$acc = ($acc << 8) | ord($payloadBytes[$i]);
		$bits += 8;
		while ($bits >= 5) {
			$bits -= 5;
			$data[] = ($acc >> $bits) & 31;
		}
	}
	if ($bits > 0) {
		$data[] = ($acc << (5 - $bits)) & 31;
	}

	$hrpExp = array();
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) >> 5; }
	$hrpExp[] = 0;
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) & 31; }

	$const = $useBech32m ? 0x2bc830a3 : 1;
	$poly = t_bech32_polymod(array_merge($hrpExp, $data, array(0, 0, 0, 0, 0, 0))) ^ $const;
	$checksum = array();
	for ($i = 0; $i < 6; $i++) {
		$checksum[] = ($poly >> (5 * (5 - $i))) & 31;
	}

	$out = $hrp . '1';
	foreach (array_merge($data, $checksum) as $d) {
		$out .= $charset[$d];
	}
	return $out;
}

// CashAddr encoder (40-bit polymod, distinct from bech32's 30-bit one), so
// token-aware vectors can be generated rather than copied. Self-checked below
// by reproducing the type-0 spec vector from the same hash.
function t_cashaddr_encode($prefix, $type, $hash) {
	$charset = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l';
	$sizeBits = array(20 => 0, 24 => 1, 28 => 2, 32 => 3, 40 => 4, 48 => 5, 56 => 6, 64 => 7);
	$payload = chr(($type << 3) | $sizeBits[strlen($hash)]) . $hash;

	$data = array(); $acc = 0; $bits = 0;
	for ($i = 0, $len = strlen($payload); $i < $len; $i++) {
		$acc = ($acc << 8) | ord($payload[$i]);
		$bits += 8;
		while ($bits >= 5) { $bits -= 5; $data[] = ($acc >> $bits) & 31; }
	}
	if ($bits > 0) { $data[] = ($acc << (5 - $bits)) & 31; }

	$pre = array();
	for ($i = 0; $i < strlen($prefix); $i++) { $pre[] = ord($prefix[$i]) & 31; }
	$pre[] = 0;

	$c = 1;
	foreach (array_merge($pre, $data, array(0, 0, 0, 0, 0, 0, 0, 0)) as $d) {
		$c0 = $c >> 35;
		$c = (($c & 0x07ffffffff) << 5) ^ $d;
		if ($c0 & 0x01) { $c ^= 0x98f2bc8e61; }
		if ($c0 & 0x02) { $c ^= 0x79b76d99e2; }
		if ($c0 & 0x04) { $c ^= 0xf33e5fb3c4; }
		if ($c0 & 0x08) { $c ^= 0xae2eabe2a8; }
		if ($c0 & 0x10) { $c ^= 0x1e4f43e470; }
	}
	$poly = $c ^ 1;

	$out = '';
	foreach ($data as $d) { $out .= $charset[$d]; }
	for ($i = 0; $i < 8; $i++) { $out .= $charset[($poly >> (5 * (7 - $i))) & 31]; }
	return $prefix . ':' . $out;
}

// mutate one character (index from the end) within the given charset
function t_mutate($address, $charset, $fromEnd = 3) {
	$i = strlen($address) - $fromEnd;
	$replacement = $charset[(strpos($charset, $address[$i]) + 1) % strlen($charset)];
	$address[$i] = $replacement;
	return $address;
}

