/**
 * Offline regression test for wallet-address validation (NMM_Address via
 * NMM_Cryptocurrencies::is_valid_wallet_address).
 *
 * What this pins (the P0 finding it guards against): the old per-coin checks
 * were unanchored, checksum-free preg_matches, so all of the following were
 * ACCEPTED and would silently collect customer funds into unspendable
 * outputs: truncated BTC addresses, 'addr?x=1' (query injection into the
 * explorer URLs), 'hello bc1q...' (ungrouped alternation matched anywhere),
 * and bad-checksum DOGE addresses. Every one of those classes must fail now:
 *
 *  - base58check coins (BTC/LTC/DOGE/DASH/BCH-legacy/DGB/QTUM/XMY/BTX/TRX/..):
 *    real base58 decode + double-SHA256 4-byte checksum + version byte.
 *  - bech32/bech32m (BIP-173/350): checksum, no mixed case, witness rules.
 *  - CashAddr (BCH): polymod checksum, with/without 'bitcoincash:' prefix.
 *  - pattern-only coins (ETH/XRP/XMR/SOL/...): anchored ^...$ regexes.
 *
 * TAPROOT DECISION: witness v1 'bc1p...' (bech32m) IS ACCEPTED for merchant
 * wallet addresses. These are Classic/Autopay RECEIVING addresses - any
 * modern wallet can pay a taproot output, and the verification explorers the
 * plugin queries (mempool.space, blockstream.info, blockcypher) all index
 * them. Rejecting them would push merchants with modern wallets back to
 * address reuse on legacy formats for no safety benefit. Witness v0 encoded
 * as bech32m, and v1 encoded as bech32, are rejected per BIP-350.
 *
 * Test-vector strategy: valid vectors are either (a) well-known public
 * reference addresses, (b) the independently verified zero-hash160 addresses
 * pinned by tests/test-hd-addrtype.php, or (c) generated by the tiny
 * encoders below - which are themselves cross-checked against known-good
 * strings ('1111111111111111111114oLvT2', the BIP-173 P2WPKH example) before
 * any generated vector is trusted. Invalid vectors (mutation / truncation /
 * affix / wrong network / wrong case) are derived mechanically from the
 * valid ones so every coin gets the same hostile treatment.
 *
 * Usage: php tests/test-address-validation.php   (pure PHP, no network,
 *        no GMP/BCMath required - the validator is deliberately extension-free)
 */

