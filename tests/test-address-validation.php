function t_b58check_encode($versionPrefix, $hash) {
	$payload = $versionPrefix . $hash;
	$full = $payload . substr(hash('sha256', hash('sha256', $payload, true), true), 0, 4);

	$alphabet = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
	$digits = array(0);
	for ($i = 0, $len = strlen($full); $i < $len; $i++) {
		$carry = ord($full[$i]);
		for ($j = 0, $n = count($digits); $j < $n; $j++) {
			$carry += $digits[$j] << 8;
			$digits[$j] = $carry % 58;
			$carry = intdiv($carry, 58);
		}
		while ($carry > 0) {
			$digits[] = $carry % 58;
			$carry = intdiv($carry, 58);
		}
	}
	$out = '';
	for ($i = 0; $i < strlen($full) && $full[$i] === "\x00"; $i++) {
		$out .= '1';
	}
	for ($i = count($digits) - 1; $i >= 0; $i--) {
		$out .= $alphabet[$digits[$i]];
	}
	return $out;
}

function t_bech32_polymod($values) {
	$gen = array(0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3);
	$chk = 1;
	foreach ($values as $v) {
		$top = $chk >> 25;
		$chk = (($chk & 0x1ffffff) << 5) ^ $v;
		for ($i = 0; $i < 5; $i++) {
			if (($top >> $i) & 1) {
				$chk ^= $gen[$i];
			}
		}
	}
	return $chk;
}

function t_bech32_encode($hrp, $witnessVersion, $programBytes, $useBech32m) {
	$charset = 'qpzry9x8gf2tvdw0s3jn54khce6mua7l';

	// 8-bit -> 5-bit with padding
	$data = array($witnessVersion);
	$acc = 0; $bits = 0;
	for ($i = 0, $len = strlen($programBytes); $i < $len; $i++) {
		$acc = ($acc << 8) | ord($programBytes[$i]);
		$bits += 8;
		while ($bits >= 5) {
			$bits -= 5;
			$data[] = ($acc >> $bits) & 31;
		}
	}
	if ($bits > 0) {
		$data[] = ($acc << (5 - $bits)) & 31;
	}

	$hrpExp = array();
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) >> 5; }
	$hrpExp[] = 0;
	for ($i = 0; $i < strlen($hrp); $i++) { $hrpExp[] = ord($hrp[$i]) & 31; }

	$const = $useBech32m ? 0x2bc830a3 : 1;
	$poly = t_bech32_polymod(array_merge($hrpExp, $data, array(0, 0, 0, 0, 0, 0))) ^ $const;
	$checksum = array();
	for ($i = 0; $i < 6; $i++) {
		$checksum[] = ($poly >> (5 * (5 - $i))) & 31;
	}

	$out = $hrp . '1';
	foreach (array_merge($data, $checksum) as $d) {
		$out .= $charset[$d];
	}
	return $out;
}

// mutate one character (index from the end) within the given charset
function t_mutate($address, $charset, $fromEnd = 3) {
	$i = strlen($address) - $fromEnd;
	$replacement = $charset[(strpos($charset, $address[$i]) + 1) % strlen($charset)];
	$address[$i] = $replacement;
	return $address;
}

